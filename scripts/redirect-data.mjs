import fs from 'node:fs/promises';

// Plain ESM also works with the older compiler used by Pages Git builds.
const read = async name => JSON.parse(await fs.readFile(new URL(`../src/data/${name}.json`, import.meta.url), 'utf8'));
const ids = await read('legacy-ids');
const media = await read('legacy-media');
await fs.writeFile(new URL('../src/data/legacy-redirects.js', import.meta.url),
  `// Generated by scripts/redirect-data.mjs; edit the source JSON files.\nexport const ids = ${JSON.stringify(ids)};\nexport const media = ${JSON.stringify(media)};\n`);
